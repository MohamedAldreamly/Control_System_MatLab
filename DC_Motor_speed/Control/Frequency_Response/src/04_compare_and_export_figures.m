%% Recompute all 3 frequency-domain designs independently
s = tf('s');
P_motor = 2/(s^2 + 12*s + 20.02);

% P-only: target phase margin PM_P (degrees).
% At crossover: w^2 - 12*cot(PM_P)*w - 20.02 = 0.
% Choose its positive root; K_P = 1/|P(j*w_P)|.
PM_P = 60;
b_P = 12*cotd(PM_P);
w_P = (b_P+sqrt(b_P^2+4*20.02))/2;
K_P = sqrt((20.02-w_P^2)^2+(12*w_P)^2)/2;
L_P = K_P*P_motor;
T_P = feedback(L_P,1);

% Lag only: 5 rad/s crossover; -15 degrees phase; 0.5% error.
% Q = K*z/p = (1/e_target-1)/P(0).
w_lag = 5;
e_target = 0.005;
Q = (1/e_target-1)/dcgain(P_motor);
% Magnitude at crossover: M_lag = 1/|P(j*w_lag)|.
M_lag = 1/abs(evalfr(P_motor,1j*w_lag));
% Desired Lag phase = -15 deg: M_lag*exp(-j*15deg)=R+j*I.
R = M_lag*cosd(15);
I = -M_lag*sind(15);
% Real/imaginary matching: p = w*I/(R-Q), K=R+I*p/w, z=Q*p/K.
p = w_lag*I/(R-Q);
K = R+I*p/w_lag;
z = Q*p/K;
L_lag = K*(s+z)/(s+p)*P_motor;
T_lag = feedback(L_lag,1);

% Lead-lag: 10 rad/s crossover; 65 deg PM; -5 deg lag; 0.5% error.
% lead_phase = PM_target - [180 + angle(P(j*w_total))] + lag_budget.
w_total = 10;
PM_total_target = 65;
lag_budget = 5;
P_w = evalfr(P_motor,1j*w_total);
lead_phase = PM_total_target-(180+angle(P_w)*180/pi)+lag_budget;
% Lead phase max: alpha=(1-sin(lead_phase))/(1+sin(lead_phase)).
alpha = (1-sind(lead_phase))/(1+sind(lead_phase));
% Phase peak at w_total: tau = 1/[w_total*sqrt(alpha)].
tau = 1/(w_total*sqrt(alpha));
C_lead = (1+tau*s)/(1+alpha*tau*s);
% Remaining Lag+K magnitude = 1/[|P(j*w_total)|*|C_lead(j*w_total)|].
M_total = 1/(abs(P_w)*abs(evalfr(C_lead,1j*w_total))); 
% Lag+K angle = -lag_budget: R=M*cos(lag_budget), I=-M*sin(lag_budget).
R = M_total*cosd(lag_budget);
I = -M_total*sind(lag_budget);
% Same analytic pole, gain and zero identities used in Stage 2.
p = w_total*I/(R-Q);
K = R+I*p/w_total;
z = Q*p/K;
L_total = K*(s+z)/(s+p)*C_lead*P_motor;
T_total = feedback(L_total,1);

